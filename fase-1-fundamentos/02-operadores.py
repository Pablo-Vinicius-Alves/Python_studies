print(10 + 3)  
print(10 - 3)   
print(10 * 3)   
print(10 / 3)   # 3.333
print(10 // 3)  # 3  (divisão inteira)
print(10 % 3)   # 1 
print(10 ** 2)  # 100 (potência)

print(5 == 5)   # True
print(5 != 3)   # True
print(5 > 3)    # True
print(5 >= 5)   # True

idade = 20
temCarteira = True

print(idade >= 18 and temCarteira) # retorna true, as duas condições precisam ser verdadeiras
print(idade >= 18 or temCarteira) # retorna true, basta uma das condições ser verdadeira
print(not temCarteira) # retorna falso pois tem carteira

